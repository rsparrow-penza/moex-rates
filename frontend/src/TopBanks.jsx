const fmtInt = (n) => Math.round(n).toLocaleString('ru-RU')

// Денег в базе нет (банк не публикует форму) — прочерк во всех колонках.
const dash = (v) => v === null || v === undefined

// Активы хранятся в трлн ₽; для мелких банков правдоподобнее млрд.
const fmtAssets = (trln) => dash(trln) ? '—' : trln >= 1
  ? `${trln.toFixed(1).replace('.', ',')} трлн`
  : `${fmtInt(trln * 1000)} млрд`
// Прибыль — млрд ₽ с начала года; сотни миллионов показываем в млн, знак сохраняем.
const fmtProfit = (mlrd) => dash(mlrd)
  ? '—'
  : Math.abs(mlrd) < 1
    ? `${fmtInt(mlrd * 1000)} млн`
    : (+mlrd.toFixed(1)).toLocaleString('ru-RU')
// Капитал/вклады/средства — трлн ₽ (колонка пустая = нет данных → прочерк).
const fmtTrln = (trln) => dash(trln)
  ? '—'
  : trln >= 1
    ? `${trln.toFixed(1).replace('.', ',')} трлн`
    : `${fmtInt(trln * 1000)} млрд`

